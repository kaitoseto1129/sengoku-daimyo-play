export function kenshinStep(ctx) {
  const { tedoHold, RG, RR } = ctx;
  return tedoHold({ at: RG, dur: 55, r: 12, stopSignal: true, title: '謙信の旗本', sub: '毘の旗が渡り口へ', label: '北岸の篝火', obj: '火で踏みとどまり、謙信の旗本を止めよ',
    say: [['組頭', '毘の旗じゃ！　謙信の旗本が来る。背は川じゃ、退く所は無いぞ！']],
    waves: [
      { t: 2, say: ['足軽', '馬じゃ！　毘の旗の騎馬が真っ直ぐ来よる！'], foes: () => [{ name: '謙信の旗本の騎馬', from: RR.front, list: [uS(1, { horse: true }), uC(4)] }] },
      { t: 14, say: ['組頭', '後ろに旗本の槍が続く！　川へ押し込む気じゃ。槍を下ろすな！'], foes: () => [{ name: '謙信の旗本の槍', from: RR.fl, list: [uS(1), uA(6)] }] },
    ], reward: '謙信の旗本の寄せを、濁流を背に受け止めた' });
}
