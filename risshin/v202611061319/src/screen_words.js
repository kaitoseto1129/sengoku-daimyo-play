// 画面の言葉をそろえる（kaito 11/5 九の1・九の7「距離は m」「ひらがなに開いた言葉は漢字に戻す」）。全戦に効く。
//   画面へ字を書く所（hud_common の setText・setHtml、目標の表、行き先の▼）で一度だけ通す。字が変わった時だけ走る。
const WORDS = [
  ['いのち', '命'], ['たいりょく', '体力'], ['げんき', '元気'], ['やじるし', '矢印'], ['はたまで', '旗まで'],
  ['たおせ', '倒せ'], ['たおす', '倒す'], ['たおし', '倒し'], ['たたかう', '戦う'], ['たたかえ', '戦え'],
  ['すすむ', '進む'], ['すすめ', '進め'], ['にげる', '逃げる'], ['にげろ', '逃げろ'], ['にげよう', '逃げよう'],
  ['まもる', '守る'], ['まもれ', '守れ'], ['とめよう', '止めよう'], ['かまえる', '構える'], ['つぎの', '次の'],
  ['すきに つこう', '隙に突こう'], ['を むこう', 'を向こう'], ['さがる', '下がる'], ['少しまつ', '少し待つ'],
];
const ANY = new RegExp(WORDS.map(([k]) => k).join('|'), 'g');
const MAP = new Map(WORDS);
// 歩の数は、どの所でもメートルで数えた数（一歩を〇・七五 m で割った所は、割らずに書く）
const STEP = /(\d+)\s*歩/g;

export function screenWords(s) {
  if (typeof s !== 'string' || !s) return s;
  if (s.includes('歩')) s = s.replace(STEP, '$1m');
  ANY.lastIndex = 0;
  return ANY.test(s) ? s.replace(ANY, (w) => MAP.get(w)) : s;
}
