// ======================================================================
// 手取川の戦い　渡った後の余韻（最後の30秒。b_tedorigawa.js の win から入れる）
// 史実：謙信は「存外に手弱き」と記し、上杉勢は手取川の北岸で勝ちを収めた。柴田は御幸塚・大聖寺に兵を残して退いた。
// 遊び：渡り切ってもすぐ札へ行かない。北岸から上杉の勝鬨が雨の中を渡って来て、濁流の音と、手負いを担ぐ列で締める（約30秒）。
// ======================================================================
import { sfx } from '../audio.js';

export const YOIN_SEC = 30;

export function install(rt, ctx) {
  const { FORD } = ctx;
  // 余韻も操作中の戦場。倒れた後や再試行の札へ、後続の声を重ねない。
  const after = (sec, fn) => rt.after(sec, () => {
    if (rt.over || rt.result?.down || !rt.player.u.alive || rt.player.u.hp <= 0) return;
    fn();
  });
  after(12, () => { rt.army.play?.('toki', { x: FORD.x, z: FORD.z - 30 }, 1.4); sfx('toki', 0.6); });
  after(14, () => rt.say('上杉の足軽', 'えい、えい、おう！　えい、えい、おう！', 3.5));
  // 11/17 K355（漫画の手がかり：信長の忍び16巻・信長協奏曲12巻 第66話）：謙信は濁流の先まで追わず、北岸で酒を開いて勝ちを祝い、越後へ帰る。
  after(16.5, () => rt.say('物見', '上杉は川を越えて来ぬ。北の岸で篝を焚き、酒を開いておるようじゃ', 2.5));
  after(19, () => { sfx('wade', 0.6); rt.say('足軽', '川に呑まれた者が、まだ……。振り向くな、歩け', 4); });
  // 指示書（tedorigawa_spec_1109.md 戦後）：数を確かめると行方不明が多い。討死と行方不明を分けて言う（imac-own3 11/15）。
  after(23.5, () => rt.say('組頭', '組の者を数えよ。……藤七が戻らぬ。討たれたか、川に呑まれたか', 3.5));
  after(27.5, () => rt.say('組頭', '手負いを担げ。生きて帰るのが、殿の働きじゃ', 2.5));
}
