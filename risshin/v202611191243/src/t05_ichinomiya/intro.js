// 一宮城 ① 0〜3分の足し：秀長が総大将として阿波に入り、同じ時に讃岐・伊予からも羽柴の大軍が四国へ入っている（docs/toyo15_plan_1108.md の 8）。
// 河原の向こうを行く別の手（軽い大軍）と、使番の別戦線の知らせ。本物の兵は増やさない。
import { host, reports } from '../toyo15/kit.js';

export function install(rt) {
  // 隊の幅と移動先も含め、西の谷へ進む本人から百五十m以上離す。
  // 後詰めが出だしの八十m以内に見える配置では、近くに軽い兵を出さない直しが戻ってしまう。
  const A = host(rt, { x: 260, z: -150, w: 60, d: 26, count: 800, facing: -0.3, seed: 5101 });   // 秀長の本隊、東の大手へ
  const B = host(rt, { x: 240, z: -260, w: 70, d: 24, count: 700, facing: 0.2, seed: 5102 });    // 後から渡ってくる手
  host(rt, { x: 260, z: -40, w: 50, d: 30, count: 600, facing: -1.6, seed: 5103 });            // 大手の麓の囲み
  A.advance(60, 160); B.advance(50, 180);
  reports(rt, [
    [20, '使番', '讃岐の宇喜多秀家・黒田官兵衛の勢、屋島から阿波へ回ります！'],
    [70, '使番', '伊予の小早川隆景の勢、金子城を囲みました！'],
    // 11/18 K306・K355（センゴク権兵衛5巻）：高い井楼の櫓から山の上の城を見下ろして攻めた。植田城の罠は官兵衛がわざと攻めずに素通りした
    [104, '足軽', '大手の井楼の櫓が、城の塀より高う組み上がったぞ。城の内が丸見えじゃ'],
    [190, '使番', '長宗我部親泰、牛岐城を捨てて土佐の方へ退きました'],
    [140, '使番', '大手の秀長様の本隊、明神丸の下まで寄せております'],
    [228, '使番', '大手の本隊、明神丸の外の柵を破りました！'],   // 11/19 k41：250秒は押し戻しの段の始めと重なった
    [360, '使番', '讃岐の植田城は、官兵衛様が罠と見て攻めずに素通り。宇喜多勢も一宮へ向かいます'],
    [520, '使番', '長宗我部の木津城・岩倉城も、次々に開け渡しております'],
  ]);
}
