// ======================================================================
// 有岡城 ②の後半：惣構えの通りを押さえる（木戸の内の番兵を退けた後・約3分〜6分）
// 構成：docs/oda15_plan_1108.md の 27（3〜6 総構え外郭攻略）。
// 木戸の先の通りの角で、砦の残兵と塀の鉄砲衆を退ける。途中で「官兵衛は生きている」と牢番の口から知らせが入る。
// 段の作りは有岡の ariFight（b_arioka.js）をそのまま使い、兵は準備の時に置いた荒木勢（prepareDefenders）を動かすだけ。
// ======================================================================
export function stages(H) {
  const { rest, ariFight, uS, uA, gunLine, GATE, TOWN_X, reinforce } = H;
  const at = { x: TOWN_X - 24, z: GATE.z };
  return [
    rest({ dur: 8, at, label: '惣構えの通り', say: [['滝川一益', '砦は取った。次は惣構えの通りじゃ。角の荒木勢と塀の鉄砲を黙らせよ']], fn: (rt) => reinforce(rt, at, 10) }),
    ariFight({ at, r: 16, title: '惣構えの通り', sub: '砦の残兵と塀の鉄砲衆が、通りの角を塞ぐ', obj: () => '惣構えの通りの角を押さえよ',
      say: [['滝川の組頭', '塀の陰を進め。鉄砲は撃ち終わりを狙え', 4]],
      foes: () => [
        { name: '砦の残兵', from: { x: TOWN_X + 30, z: GATE.z + 4 }, list: [uS(1), uA(6)], morale: 70 },   // 木戸の戦に巻き込まれない東の通りに控える
        gunLine('惣構えの塀の鉄砲衆', { x: TOWN_X + 40, z: GATE.z - 6 }, 3, {}),
      ],
      later: [
        { t: 28, say: ['足軽', '牢番を捕らえたぞ！　官兵衛殿は生きて、城の牢におると！'], foes: () => [] },
        { t: 40, title: '塀沿いの新手', sub: '北の塀沿いから、荒木勢が通りへ下りる', say: ['滝川の組頭', '北から新手じゃ！　角を渡すな！'],
          foes: () => [{ name: '北の塀沿いの荒木勢', from: { x: TOWN_X - 12, z: -74 }, list: [uS(1), uA(5)], morale: 75 }] },
      ],
      max: 200, reward: '惣構えの通りを押さえた',
      // 11/9 二巡（豊臣A）：塀の陰の鉄砲衆を討ち尽くすまで続き、act の流しで七分半この段に止まった（15分の構成で三分の所）。四分で次へ
      lenient: true, limit: 240, passOnLimit: true, onEnd: () => {} }),   // 11/9 見回り 織田F：期限で負けにせず次へ（act の流しが期限切れで任務失敗していた）
  ];
}
