// 戦の id から引く（接頭の「k06_」「d01_」「t01_」などを外した名でも引く）
export function battleLineEn(key) {
  if (!key) return '';
  if (BATTLE_LINE_EN[key]) return BATTLE_LINE_EN[key];
  const bare = String(key).replace(/^[a-z]\d+[a-z]?_/, '');
  const hit = Object.keys(BATTLE_LINE_EN).find((k) => k.replace(/^[a-z]\d+[a-z]?_/, '') === bare);
  return hit ? BATTLE_LINE_EN[hit] : '';
}
