// ======================================================================
// 天王寺・岡山の戦い　使番の続けての知らせ（K325 要件書 5-8・K337 照らしの係 11/16）
// 「第一陣突破！」「第二陣も下がっています！」「真田勢、本陣へ！」を③の段で順に言わせ、前線が一枚ずつ破られていくのを声で分からせる。
// 真田・毛利の動き（hq_rush.js・mori_push.js）には触らない。言った印は rt.flags に置く（直前から再開の写しに入る）。
// ======================================================================
export function tick(rt) {
  const F = rt.flags;
  if (F.ending || F.step !== 3) return;
  const S = F.k325t ||= {};
  const t = rt.t - (F.tS || 0);
  if (!S.a && t > 3.5) { S.a = true; rt.say('使番', '第一陣突破！　先手の備が崩れました！', 2.6); }
  if (!S.b && t > 22) { S.b = true; rt.say('使番', '第二陣も下がっています！', 2.4); }
  if (!S.c && S.b && (t > 32 || (F.hqThreat || 0) >= 60)) { S.c = true; rt.say('使番', '真田勢、本陣へ！', 2.4); }
}
