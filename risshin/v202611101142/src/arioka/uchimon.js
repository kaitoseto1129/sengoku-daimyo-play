// 侍町の奥（本丸へ向かう通り）の木戸で、もう一度内応の者が門を開ける。木戸の番兵を退け、本丸への道を押さえる。
// 着いた所で、牢から官兵衛を連れ出したと知らせが来る（win の官兵衛の場面へつなぐ）。
// 段の作りは有岡の ariFight を使い、兵は準備の時に置いた荒木勢を動かすだけ。
