// 大河内城 15分の構成（docs/oda15_plan_1108.md 7）　⑤「戦闘停止・和睦交渉・信雄養子入り・力だけでは落とせない城」（12〜15分）
// 和睦の札（peace）の後、すぐ結果へ行かず三十秒ほど余韻を見せる。開いた木戸から城を受け取る組・槍を収める兵・語り。
// 呼び方：b_okawachi.js の peace() で play(rt, ctx, at)。返す数は finish の秒。
// ======================================================================
export function play(rt, ctx, at) {
  const { speaker } = ctx;
  const live = () => !rt.ended;
  rt.after(at + 6, () => { if (live()) rt.say('足軽', '木戸が開いた……攻め落とせなんだ城が、話し合いで開くのか', 3.6); });
  rt.after(at + 11, () => { if (live()) rt.say(speaker, '殿の次男、茶筅丸様が北畠具房殿の養子に入る。城は和睦で開くのじゃ', 4); });
  rt.after(at + 17, () => { if (live()) rt.say('組頭', '力だけでは落とせぬ城もある。覚えておけ', 3.4); });
  rt.after(at + 22, () => { if (live()) rt.say('', '――茶筅丸は北畠具房の養子となり、のちの織田信雄となる', 4.2); });
  return at + 28;
}
