// 11/18 cloud-31：音だけの一斉射だった。狭間の近く（三十五歩内）の味方の鉄砲が、堀の島津勢へ本当に撃つ（army_ranged の scriptSalvo）
function salvoAt(rt, at) {
  const A = rt.army, foes = A.groups.filter((g) => g.team === 1 && g.count && !g.routed);
  for (const g of A.groups) {
    if (g.team !== 0 || !g.count || g.routed || g.isPlayerSquad) continue;
    const c = g.center();
    if (Math.hypot(c.x - at.x, c.z - at.z) < 35) A.scriptSalvo?.(g, foes, 5);
  }
}
