// ======================================================================
// 第二次木津川口 ③の段：乗り口の守り（約4分〜9分）の中ほどの出来事
// 構成：docs/oda15_plan_1108.md の 25（6〜9 接舷・船上近接戦）と共通方針 2「何も変わらない時間を4分以上作らない」。
// 乗り口の段は九分まで続くので、中ほどで二度だけ戦況を変える（敵の体力は増やさない。寄せる船と声で変える）。
//   ・段に入って二分：南の沖から新手の小早がまとめて寄せる（空いた乗り口へ一斉に）
//   ・段に入って三分半：沖の奥の大将の関船が櫓で動き出す（④の大将船への伏線）
// ======================================================================
export function tick(rt, ctx, elapsed) {
  const F = rt.flags;
  if (F.ending || !rt.player.u.alive) return;
  const S = F.kzNori || (F.kzNori = { a: false, b: false });
  if (!S.a && elapsed >= 120) {
    S.a = true;
    rt.say('物見', '南の沖から新手の小早じゃ！　鉤縄を手に、まとめて漕ぎ寄せて来るぞ！', 3.5);
    rt.army.playFar('sig_kakari_taiko', { x: -60, z: 95 }, 0.85);
    ctx.surge(rt);
  }
  if (!S.b && elapsed >= 210) {
    S.b = true;
    rt.army.playFar('horagai', { x: -120, z: 110 }, 0.8);
    rt.say('九鬼嘉隆', '沖の奥の大関船が櫓を揃えた。大将の船が寄せて来るぞ。乗り口を押し返したら、西の大筒へ回れ！', 4);
  }
}
