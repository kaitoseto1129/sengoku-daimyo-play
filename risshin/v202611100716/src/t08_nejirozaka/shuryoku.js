// ======================================================================
// 根白坂　後半（9〜14分）：島津家久・義珍の主力の総がかり
//   ④「右の堀を守れ」：台地の東の縁から家久の手が右の堀を越えて来る
//   ⑤「土橋へ戻れ」：中央の土橋に義珍の旗本の新手。藤堂・戸川の援け → 黒田・小早川が島津の横を突くまで持つ
// 呼び方：steps の忠隣の段の後に main(rt, H) の物を並べる。
// ======================================================================
import { sfx } from '../audio.js';

export const EAST = { x: 36, z: -4 };   // 右の堀の内（東の塀の内）

export function main(rt, H) {
  const { hold, rest, uS, uA, uG, from, BREACH, STEP_TEXT } = H;
  return [
    rest({ dur: 6, heal: 0.3, say: [['物見', '坂の下の松明が増えた！　家久・義珍の本手が動きました'], ['宮部継潤', '右の堀じゃ。東の縁から回るぞ']] }),
    // ④ 右の堀：家久の手が東の台地の縁から堀を越える。途中で中央にも寄せが来る（「中央へ戻れ」の伏線）
    hold({ at: EAST, dur: 100, limit: 135, r: 13, label: '右の堀', obj: STEP_TEXT[3],
      say: [['宮部継潤', '右の堀を守れ！　家久の手が東から来る！']],
      waves: [
        // off は持ち場 EAST からの差。絶対座標を入れると東の塀より外へ二重にずれる。
        { t: 3, say: ['足軽', '十文字の旗が堀に飛び込んだ！'], foes: () => [{ name: '島津家久の先手', from: { x: 90, z: 30 }, off: { x: 4, z: 14 }, list: [uS(3), uA(12)], noRout: 20 }] },
        { t: 28, say: ['鉄砲頭', '堀の底に詰まった。狭間から放て！'], foes: () => { rt.army.play('volley', { x: 36, z: 8 }, 1.3); return [{ name: '島津家久の二の手', from: { x: 84, z: 46 }, off: { x: -2, z: 16 }, list: [uS(2), uA(10), uG(2)] }]; } },
        { t: 56, say: ['足軽', '塀を越えた者がおる！　槍を入れよ！'], foes: () => [{ name: '塀を越えた島津勢', from: { x: 70, z: -20 }, off: { x: 6, z: -8 }, list: [uS(3), uA(8)], noRout: 15 }] },
      ],
      noRefill: true, reward: '右の堀で家久の手を押し返した' }),
    rest({ dur: 5, heal: 0.25, say: [['使番', '土橋に義珍の旗本が！　中央が破られまする！'], ['宮部継潤', '中央へ戻れ！　土橋を守れ！']] }),
    // ⑤ 土橋へ戻る：義珍の旗本の新手。藤堂・戸川が来て、最後に黒田・小早川が島津の横を突く
    hold({ at: { x: BREACH.x, z: BREACH.z - 4 }, dur: 110, limit: 150, r: 14, label: '土橋の塀', obj: STEP_TEXT[4],
      waves: [
        { t: 2, say: ['足軽', '島津の本手じゃ！　坂の下から新手が来る！'], foes: () => [{ name: '島津義珍の旗本', from: from(-6), list: [uS(4), uA(12)], noRout: 30 }] },
        { t: 30, foes: () => { H.todoArrive(rt); return [{ name: '島津の新手', from: from(20), off: { x: 10, z: 0 }, list: [uS(2), uA(10), uG(3)] }]; } },
        { t: 62, say: ['足軽', '西の塀にも島津が回った！'], foes: () => [{ name: '西から回った島津勢', from: { x: -78, z: -10 }, off: { x: -30, z: -10 }, list: [uS(2), uA(10)] }] },
        // 東の尾根から土橋の東脇へ歩いて着く時間を確保する。
        { t: 70, foes: () => { H.reliefArrive(rt); return []; } },
      ],
      noRefill: true, reward: '援けが来るまで土橋を守り抜いた' }),
    rest({ dur: 6, heal: 0.3, say: [['小早川隆景', '島津の横腹を突いたぞ！　崩れる！'], ['物見', '島津の松明が、坂の下へ下がっていきます']],
      fn: () => { H.retreatAll(rt); sfx('horagai', 0.8); } }),
  ];
}
