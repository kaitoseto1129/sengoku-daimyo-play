// ======================================================================
// 根白坂　始まりの段（0〜3分）：夕暮れの砦を見て回る（右の堀 → 土橋の塀）
//   空堀・板塀・鉄砲の狭間・槍の組を、宮部の侍と歩いて見せる。北の高城の囲み（秀長の本隊）は遠くの軽い大軍の押し合いで、
//   「同じ時に別の所でも何万人も戦っている」を見せる。使番が別の戦線（高城・秀吉の本隊）を知らせる。
// 呼び方：steps の頭に tour(rt, H) の二つを入れる。install(rt) は setup で一度。
// ======================================================================
import { clash } from '../b_sekigahara.js';

// 北（砦の後ろ）の高城の囲み：秀長の本隊が城の坂で城兵と押し合う（本物にはならない）
export function install(rt, H) {
  const F = rt.flags;
  try {
    F.takajoC = clash(rt, { x: 30, z: -230, facing: Math.PI, w: 70, gap0: 0, seed: 15871, noWake: true, noRout: true,
      A: { flag: 'toyotomi', armor: H.MIYABE.armor, count: 260, flagRate: 0.5, guns: true },
      B: { flag: 'shimazu', armor: H.SHIMAZU.armor, count: 120, flagRate: 0.4, guns: true } });
    rt.after(1, () => F.takajoC?.go?.());
  } catch (e) { F.takajoC = null; }
  try { rt.world.addFire(40, -250, { size: 4, h: 0.4, blackSmoke: true }); } catch (e) { /* 飾り */ }
}

// 見回り：右（東）の堀 → 受け持ちの土橋の塀
export function tour(rt, H) {
  const F = rt.flags;
  return [
    H.move({ to: { x: 34, z: -6 }, r: 7, label: '右の堀', obj: '日の暮れぬうちに、砦の右の堀と塀を見て回れ', max: 70,
      say: [['宮部の侍', '空堀は深さ一丈。土橋のほかは、堀を越えねば塀に届かぬ'], ['宮部の侍', '右の堀の先は台地の縁。島津が回り込むならここじゃ']] ,
      onEnd: () => {} }),
    // 右の堀で一息：北の高城の囲みと、坂の下の島津の気配を見せる（使番の知らせ）
    H.rest({ dur: 15, heal: 0, say: [['使番', '高城の山田有信、なお籠っております。中納言様の本隊が囲みを締めております', 3.6],
      ['宮部の侍', '北の煙が見えるか。あれが高城の囲みじゃ。こちらは一万、島津は三万五千', 3.6],
      ['物見', '坂の下の田に、旗が増えております。日が落ちれば来ましょう', 3.4], ['宮部の侍', '右の堀は台地の縁で浅い。ここを抜かれたら砦の横腹じゃ', 3.4]] }),
    H.move({ to: H.POST, r: 6, label: '土橋の塀', obj: '土橋の奥の塀の内へ入り、鉄砲衆の横に並べ', max: 70,
      say: [['宮部継潤', '鉄砲は塀の狭間へ。火縄の火を外へ見せるな'], ['足軽', '堀の底で、草が鳴っておる……']],
      onEnd: (r) => {
        if (F.guns) { F.guns.order = 'hold'; F.guns.aggro = 40; }
      } }),
    // 土橋の塀で待つ：鉄砲衆が火縄を伏せ、日が傾いていく
    H.rest({ dur: 15, heal: 0, say: [['使番', '殿下の本隊は肥後を南へ。島津はここで後詰を通さねば、薩摩まで攻められまする', 3.6],
      ['鉄砲頭', '火縄は伏せたか。引き付けてから、狭間から一度に放つ', 3.2], ['足軽', '日が沈む……。坂の下で、鎧の擦れる音がする', 3.2],
      ['宮部継潤', '島津は退く時に強い。だが攻めて来る時は、この堀が守ってくれる', 3.6]] }),
  ];
}
