// 森部 14〜15分：余韻（勝ち戦の後すぐ結果へ行かない）
//   両将が討たれ、斎藤勢は墨俣へ退いた。雨が細る中で勝鬨を三度。首実検は薬師堂の前（本体）。
//   組頭が「墨俣に砦を築けば美濃は取れる」と次の戦（墨俣）を匂わせる。二十秒余りは本人が動ける。その後に本体の finish。
// ======================================================================
import { sfx } from '../audio.js';

export function start(rt, def, C, then) {
  const F = rt.flags, v = F.m15 || (F.m15 = {});
  if (v.yoinT) return;
  v.yoinT = rt.t;
  // 共通の目標完了処理を待たせ、首実検と勝鬨の余韻が済んでから締める。
  if (!rt.over) rt._closing = { at: rt.t + 16, info: { scriptedEnd: true }, delay: 1 };
  // 決着後も予約の時計は進む。退場・再開した戦へ古い声や締めを持ち越さない。
  const after = (t, fn) => rt.after(t, () => {
    if (!rt.over && !rt.ended && rt.flags === F && F.m15 === v && F.ending) fn();
  });
  // 本体の仲間の話と首実検の下知（九・五秒から五秒間）を最後まで見せ、掛け声と応答も重ねない。
  const toki = (t, s) => after(t, () => { rt.army.playFar?.('toki', rt.player.u.pos, 1.4); sfx('taiko', 1); rt.say('組頭 源八（げんぱち）', s, 1.3); });
  // 11/13 K090（kaito「全部果たしたらその場で締め場面→数秒で勝利」）：三十一秒の余韻を十五秒へ縮めた。勝鬨は二度。
  toki(1.2, 'えい、えい！');
  after(2.6, () => rt.say('織田の兵', 'おう！', 1.3));
  toki(6, 'えい、えい！');
  after(7.4, () => rt.say('織田の兵', 'おおう！', 1.6));
  after(10, () => rt.say('足軽', '斎藤勢は墨俣の方へ逃げてゆく……墨俣は川の中洲じゃ。あそこに砦があれば美濃は目の前ぞ', 4));
  after(15, () => { if (!rt.over) { rt._closing = null; then(); } });
}
