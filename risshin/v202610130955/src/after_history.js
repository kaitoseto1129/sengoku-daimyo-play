// 戦が終わった時だけ呼ぶ。織田家編以外の説明は元のまま返す。
export function afterHistory(id, mainDone, fallback) {
  if (!Object.prototype.hasOwnProperty.call(AFTER_HISTORY, id)) return fallback;
  const result = mainDone ? 'この遊びでは任務を果たした。' : 'この遊びでは任務を果たせなかった。';
  return result + '史実では、' + AFTER_HISTORY[id];
}
