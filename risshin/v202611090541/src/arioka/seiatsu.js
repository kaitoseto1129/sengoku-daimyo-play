// 有岡城 ④の後：侍町の焼け跡を改める（約11分〜13分）
// 構成：docs/oda15_plan_1108.md の 27（12〜15 城内制圧・官兵衛救出・有岡城陥落の伏線）。
// 辻を守った後、焼けた侍町に隠れた荒木勢を改める。降る者は斬らない。捕らえた侍が村重の脱出を語る。
// 段の作りは有岡の ariFight（b_arioka.js）を使い、兵は準備の時に置いた荒木勢を動かすだけ。
// ======================================================================
export function stages(H) {
  const { rest, ariFight, uS, uA, gunLine, TOWN_X, reinforce } = H;
  const at = { x: TOWN_X, z: -60 };   // 辻から北の通り（侍町の奥）
  return [
    rest({ dur: 8, at, say: [['滝川一益', '辻は守った。焼け跡に隠れた者を改めよ。降る者は斬るな'], ['滝川の組頭', '火の粉に気をつけよ。屋敷の陰から撃って来るぞ', 4]], fn: (rt) => reinforce(rt, at, 10) }),
    ariFight({ at, r: 16, title: '焼けた侍町', sub: '屋敷の焼け跡に、荒木の者が隠れている', obj: () => '侍町の焼け跡に残る荒木勢を退けよ',
      say: [['足軽', '煙で前が見えぬ……誰かおるぞ！', 3.5]],
      foes: () => [
        { name: '焼け跡に隠れた荒木勢', from: { x: TOWN_X, z: -100 }, list: [uS(1), uA(6)], morale: 45 },   // 辻の戦に巻き込まれない奥に置く
      ],
      later: [
        { t: 20, say: ['捕らえた荒木の侍', '村重様は九月に、わずかな供と尼崎へ落ちられた……我らは捨てられたのじゃ'], foes: () => [] },
        { t: 34, title: '屋敷の陰の鉄砲', sub: '焼け残った屋敷から、最後の鉄砲が鳴る', say: ['滝川の組頭', '屋敷の陰じゃ！　回り込め！'],
          foes: () => [gunLine('焼け残った屋敷の鉄砲', { x: TOWN_X + 4, z: -118 }, 3, {})] },
        { t: 62, title: '本丸へ落ちそこねた者', sub: '本丸の堀へ逃げ遅れた荒木勢が、最後に打って出る', say: ['滝川の組頭', '逃げ場を失った者どもじゃ。囲んで槍を下ろさせよ'],
          foes: () => [{ name: '本丸へ落ちそこねた荒木勢', from: { x: TOWN_X - 4, z: -130 }, list: [uS(1), uA(5)], morale: 40 }] },
      ],
      max: 210, minEl: 80, reward: '侍町の焼け跡を改めた',
      lenient: true, onEnd: () => {} }),
  ];
}
